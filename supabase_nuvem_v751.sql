comment on table public.cq_orders is 'Controle Queijos — encomendas sincronizadas na nuvem';
comment on table public.cq_payments is 'Controle Queijos — recebimentos sincronizados na nuvem';
comment on table public.cq_sales is 'Controle Queijos — vendas sincronizadas na nuvem';
comment on table public.cq_expenses is 'Controle Queijos — gastos sincronizados na nuvem';
